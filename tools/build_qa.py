#!/usr/bin/env python3
"""Generate qa/scope_sheet.md and qa/open_items.md from data/*.json (never hand-edit those two)."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = json.load(open(f"{ROOT}/data/products.json"))
C = json.load(open(f"{ROOT}/data/catalogue.json"))
MISS = P["missing_marker"]

ZONES = {"A": "Below-grade", "B": "Roofs & podium decks", "C": "Wet areas & balconies",
         "D": "Water tanks / water-retaining", "E": "Joints & penetrations",
         "F": "Façades & exposed concrete", "G": "Steel & industrial"}
BRIEF = {  # brief section 4/6 membership + comparison set + my recommendation
 "PU-P150": ("Listed", "Spray polyurea (panel 1)", "KEEP"),
 "PU-P100": ("Not listed (proposed pair)", "Spray polyurea (panel 1, panel 2)", "APPROVE?"),
 "PU-P60":  ("Listed", "Spray polyurea (panel 1)", "KEEP"),
 "PU-H50":  ("Not listed (proposed pair)", "Spray polyurea (panel 2)", "APPROVE?"),
 "PU-C100": ("Not listed", "Liquid-applied (see note)", "APPROVE?"),
 "HS": ("Listed", "Sheet / pre-applied (HS in text table)", "KEEP"),
 "FB": ("Listed", "Sheet / pre-applied (FB vs FB-S bars)", "KEEP"),
 "FB-S": ("Listed", "Sheet / pre-applied (FB vs FB-S bars)", "KEEP"),
 "L": ("Listed as 'liquid-applied' — WRONG: TDS is a loose-laid PVC SHEET", "L vs R pair DROPPED", "DECIDE"),
 "R": ("Listed as 'liquid-applied' — WRONG: TDS is an FPO/TPO roofing SHEET", "L vs R pair DROPPED", "DECIDE"),
 "EPW": ("Listed (EPW-P / EPW-S, one TDS)", "Epoxy waterproofing (text table)", "KEEP"),
 "EN100": ("Listed", "none (single product)", "KEEP"),
 "SETSEAL-300C": ("Listed as 'joint sealant' — WRONG: cementitious waterproof coating", "Joint-sealant pair DROPPED", "DECIDE"),
 "SETSEAL-R": ("Listed as 'joint sealant' — WRONG; TDS says crystalline capillary system (brief excludes crystalline)", "Joint-sealant pair DROPPED", "DECIDE"),
 "REPCOAT": ("Listed", "Anti-carbonation (table: different methods)", "KEEP"),
 "REPCOAT-FF": ("Listed", "Anti-carbonation (table: different methods)", "KEEP"),
 "STRONGCOAT-HB": ("Listed — but TDS is a concrete FLOOR coating", "HB vs HB400 pair DROPPED", "DECIDE"),
}

def sec(title):
    return f"\n## {title}\n\n"

L = ["# Scope sheet — DCP Waterproofing & Protective Coatings film\n",
     "*Generated by `tools/build_qa.py` from `data/products.json` and `data/catalogue.json`. Phase 1 gate: nothing below is final until you approve it.*\n",
     "Source: PDFs downloaded from dcp-int.com (Qatar download pages; Lebanon page for Repcoat PU1 / S) plus the four PDFs you uploaded (`source-tds/user-supplied/`). "
     "**No PDF prints a document date**, so every `doc_date` is `NOT STATED` (see open items).\n"]

L.append(sec("1. Products with values extracted (17)"))
L.append("| Product | Brief status | Classification | Doc code | Zones (TDS-listed uses, page) | Comparison set | Rec. | Missing fields |\n|---|---|---|---|---|---|---|---|\n")
for p in P["products"]:
    zs = {}
    for u in p["uses"]:
        if u["zone"]:
            tag = "" if u["mapping"] == "TDS-LISTED" else "*"
            zs.setdefault(u["zone"], []).append(f'p{u["page"]}{tag}')
    zt = "; ".join(f"**{z}** ({', '.join(v)})" for z, v in sorted(zs.items())) or "none"
    flags = [u for u in p["uses"] if u["mapping"] in ("EXCLUDED-AREA", "NO-FILM-ZONE")]
    if flags:
        zt += " — ⚠ also lists: " + "; ".join(f'“{u["quote"]}”' for u in flags)
    miss = [k for k, v in p["values"].items() if v[0]["value"] == MISS]
    b = BRIEF[p["id"]]
    L.append(f'| {p["name"]} | {b[0]} | {p["classification"]} | {p["doc_code"]} | {zt} | {b[1]} | {b[2]} | {", ".join(miss) or "—"} |\n')
L.append("\n`*` = zone mapping is my interpretation (marked ASSUMED in products.json), e.g. swimming pools → zone D. Quotes for every use are in `data/products.json → uses[]`.\n")

L.append(sec("2. Other documents found — classification proposed for YOUR approval (values NOT extracted)"))
L.append("| Product | Proposed class | Doc code | Title as printed | Use quote (page) | Zone hint | Note |\n|---|---|---|---|---|---|---|\n")
for c in C["catalogue"]:
    q = f'“{c["use_quote"]}” (p{c["use_page"]})' if c["use_quote"] else "not read yet"
    L.append(f'| {c["name"]} | {c["proposed_classification"]} | {c["doc_code"]} | {c["title_as_printed"] or "—"} | {q} | {c["zone_hint"] or "—"} | {c["note"] or ""} |\n')

L.append(sec("3. Named in the brief but NO document found"))
for d in C["documents_not_found"]:
    L.append(f'- **{d["name"]}** — {d["reason"]}\n')
L.append("- **Aliphatic PU topcoats** — the brief names this group but no product. No TDS found says “aliphatic polyurethane”: the PU-P60/PU-H50/PU-P100/PU-P150 TDS only tell the reader to ask DCP Technical for “an aliphatic topcoat”; the method statements name *Repcoat P Ultra* (no TDS found). Repcoat P (PU, steel tanks) does not say “aliphatic”. Repcoat S is “aliphatic acrylate”. → open item.\n")
L.append("- **Strongcoat EPW-P / EPW-S** share one TDS (`Strongcoat EPW_TDS_4.pdf`); the data is stored once as `EPW`.\n")

L.append(sec("4. Zone coverage from TDS-listed uses (what the selector matrix could tick today)"))
L.append("| Zone | Products with a TDS-listed use |\n|---|---|\n")
for z, name in ZONES.items():
    ps = [p["name"] for p in P["products"] if any(u["zone"] == z for u in p["uses"])]
    L.append(f"| {z} {name} | {', '.join(ps) or '**NONE in the approved-list products**'} |\n")
L.append("\nZone **E (joints & penetrations)** has no supporting TDS among the products you listed: the two “joint sealants” are cementitious coatings. "
         "Candidates are Hydrostop HW / AW-C531 (PVC waterstops), Hyperseal DP-2010H / DPS-200 (hydrophilic), DonFlash, tapes — all in table 2 awaiting your decision. "
         "Zone **G** is supported by Strongcoat EPW and EN100 (“concrete and steel”) and Repcoat P (steel tanks); **not** by Strongcoat HB (concrete floors only).\n")

L.append(sec("5. Comparison sets — checked against the TDS"))
L.append("""| Proposed set | Verdict | Why (from the TDS) |
|---|---|---|
| Spray polyurea: PU-P150 vs PU-P60 / PU-P100 vs PU-H50 | **Keep, as two panels**: (1) P150 · P100 · P60, (2) P100 · H50 | All hot-spray polyurea/hybrid. Tensile, elongation, tear share ASTM D412 / D624, **but** P60 reports nominal ± values and the others “≥” minimums, so bars only if you accept mixing; crack bridging is reported with different cycles/widths (25 cycles no width · 10 cycles · 10 cycles @ 8 mm) → text table. |
| Sheet: HS vs FB vs FB-S | **Keep, split**: bars for FB vs FB-S only | FB and FB-S report tensile to EN ISO 12311-2 (A), watertightness to ASTM D 5385 and crack bridging to ASTM D 5385. HS reports tensile to ASTM D 412 modified / EN ISO 12311-2 Method B, so HS goes in a “different test methods” table. FB does not report elongation. |
| Liquid-applied: DonProof L vs R (+ Aquathane) | **DROP L vs R** | Both are **sheet** membranes: L = loose-laid PVC for below-grade/protected roofs; R = FPO/TPO exposed roofing. Different applications (only “Terraces” overlaps) and different tensile methods (EN 12311-2 Method B dumbbell vs (A)). A true liquid-applied set would be PU-C100 vs Aquathane R100/E400 — needs your approval of Aquathane. |
| Epoxy waterproofing: EPW-P vs EPW-S | **Keep (text table)** | One TDS, two grades; differ in colour, potable-water vs sewage/chemical use, and chemical-resistance table. No numeric property differs. |
| Joint sealants: Setseal 300C vs Setseal R | **DROP** | Neither is a joint sealant. 300C = flexible cementitious coating (EN 14891 Type CM). Setseal R = cementitious *crystalline* capillary render — and the brief excludes crystalline products. |
| Anti-carbonation: Repcoat vs Repcoat FF (vs FF Plus) | **Keep (text table)**; FF Plus has no document | Repcoat is elastomeric, EN 1504-2; carbonation shown per NT Build 372. FF reports carbonation per EN 13295 and no EN 1504-2 claim. Different methods → no bars. |
| High-build protective: Strongcoat HB (vs HB400) | **DROP both** | Titles: “high build epoxy floor coating”; every listed use is a concrete floor. Brief also excludes Strongcoat floor systems. |
| Primers by substrate condition | **Pending** | Strongcoat Primer / Primer S / Primer Range TDS found; DonProof Primer PU/EP have no TDS. Not yet read — depends on PRIMER_NAMING decision. |
""")
open(f"{ROOT}/qa/scope_sheet.md", "w").write("".join(L))

# ---------------- open items
O = ["# Open items\n\n*Generated by `tools/build_qa.py`. Items marked [DATA REQUIRED — R&D] must show a grey “Data pending” tag on screen.*\n"]
O.append(sec("A. Document-level"))
O.append("- **doc_date = NOT STATED for every document.** No DCP PDF prints an issue date, only a document code (e.g. 08-0176-QA-A-2026). The footnote “Source: <product> TDS, <doc code>, <date>” will therefore read `NOT STATED` for the date. (PDF metadata creation dates exist but are not document dates and are not used.)\n")
O.append("- Document codes of the Qatar set mostly lack the “QA” region token (e.g. 08-0199-A-2026), while the Lebanon/Jordan/other sites host other revisions of the same product. I used the Qatar set as baseline — ASSUMED. Other regional versions were NOT compared.\n")
O.append(sec("B. Missing core values ([DATA REQUIRED — R&D])"))
O.append("| Product | Doc code | Missing |\n|---|---|---|\n")
for p in P["products"]:
    miss = [k for k, v in p["values"].items() if v[0]["value"] == MISS]
    if miss:
        O.append(f'| {p["name"]} | {p["doc_code"]} | {", ".join(miss)} |\n')
O.append("\nField sets are per family (spray / sheet / liquid / cementitious) and reflect what a comparison panel would want; fields marked not-applicable are listed in `not_applicable_fields` per product.\n")
O.append(sec("C. Decisions needed"))
O.append("""1. Include or drop PU-P100, PU-H50, PU-C100 and every table-2 product (scope sheet).
2. DonProof L / R are sheets, Setseal 300C / R are not joint sealants, Strongcoat HB is a floor coating — confirm drop/keep (scope sheet §5).
3. Zone E has no TDS support in the listed products — approve waterstop/hydrophilic products or leave E out.
4. Missing documents: DonProof Primer PU, Primer EP, Repcoat FF Plus, “aliphatic PU topcoats” (which product?), Repcoat P Ultra (named by the PU-H50 method statement).
5. Brief §3.4 says show coverage as m²/kg or m²/ltr, but §3.3 says never convert. TDS print kg/m² (spray), litre/m² (acrylics). I store and will show them **as printed**. ASSUMED until you rule.
6. Swimming pools / aquariums → zone D mapping (marked ASSUMED).
7. PRIMER_NAMING stays “legacy” (default) — nothing built yet depends on it.
8. Products whose TDS also list car-park decks (PU-P150, PU-P100, PU-H50, PU-C100 “parking”, FB “underground car parks”, EPW): the car-park use will not be shown; other uses will. Confirm.
9. HS shelf life: TDS is silent (the 5-year figure in my first read belongs to DonProof R — the build check caught that).
""")
O.append(sec("D. Data-quality notes (checked, not blocking)"))
O.append("- DonProof L and R list tensile/elongation per grade; stored as printed strings with grade in the value. A chart will need a per-grade selection rule.\n- DonProof L / R “service_temp” entries are *foldability at low temperature*, not service ranges — do not use as such.\n- Older PDFs (Setseal 300C, Repcoat S/PU1) lose the “ti/fi” ligatures in text extraction; checked values are numeric so verification is unaffected.\n- The page check confirms the printed text is on the cited page; it cannot prove the number is attached to the right label — values were read by me and should be spot-checked by DCP R&D.\n")
open(f"{ROOT}/qa/open_items.md", "w").write("".join(O))
print("ok")

#!/usr/bin/env python3
"""Phase 4: generate qa/qa_report.md — every on-screen value with its source, open items, conflicts, assumptions."""
import json, os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = json.load(open(f"{ROOT}/data/products.json"))
MISS = P["missing_marker"]
byid = {p["id"]: p for p in P["products"]}
canon = lambda i: "EPW" if i in ("EPW-P", "EPW-S") else i
T = json.load(open(f"{ROOT}/data/timeline.json"))
CH = json.load(open(f"{ROOT}/data/chapters.json"))
SEL = json.load(open(f"{ROOT}/data/selector.json"))
mm = lambda s: f"{int(round(s))//60}:{int(round(s))%60:02d}"

def probe(path):
    if not os.path.exists(path): return None
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=codec_name,width,height,r_frame_rate,pix_fmt,nb_frames", "-show_entries", "format=duration,size", "-of", "json", path], capture_output=True, text=True).stdout
    ch = subprocess.run(["ffprobe", "-v", "error", "-show_chapters", "-of", "json", path], capture_output=True, text=True).stdout
    j = json.loads(out); c = json.loads(ch)
    return j, c

L = ["# QA report — DCP Waterproofing & Protective Coatings film\n\n"]
L.append("Generated by `tools/build_qa_report.py` after `npm run validate` and the renders. Every number below is copied from `data/products.json`, which is verified against the PDFs in `source-tds/` (the build fails if a printed value is not on the cited page).\n\n")

# ---- 1 outputs
L.append("## 1. Deliverables\n\n| File | Result |\n|---|---|\n")
m = probe(f"{ROOT}/out/master.mp4")
if m:
    j, c = m
    v = [s for s in j["streams"] if s.get("width")][0]
    L.append(f"| `out/master.mp4` | {v['width']}×{v['height']}, {v['r_frame_rate']} fps, {v['codec_name']} {v['pix_fmt']}, {float(j['format']['duration']):.1f} s ({mm(float(j['format']['duration']))}), {int(j['format']['size'])/1e6:.1f} MB, {len(c['chapters'])} chapter markers |\n")
for ch in T["chapters"]:
    pr = probe(f"{ROOT}/out/chapters/{ch['id']}.mp4")
    if pr:
        j, c = pr; v = [s for s in j["streams"] if s.get("width")][0]
        L.append(f"| `out/chapters/{ch['id']}.mp4` | {v['width']}×{v['height']} @ {v['r_frame_rate']}, {float(j['format']['duration']):.1f} s (planned {ch['dur']:.1f} s), {int(j['format']['size'])/1e6:.1f} MB |\n")
L.append("| `out/captions/*.srt` | master + per-chapter captions (≤12 words per cue); **no captions burned in** |\n")
L.append("| Vertical 1080×1920 cutdowns | **not made** — only after you approve the master (brief §1) |\n")
L.append("| Audio | none supplied: music slot `public/audio/music.mp3`, VO slot `public/audio/vo_en.mp3`; film renders cleanly without them |\n\n")
L.append("`out/` is git-ignored (large binaries). Re-create with `npm run render:chapters && npm run render:master`.\n\n")

# ---- 2 values
L.append("## 2. Every on-screen value and its source\n\nValue text is exactly as printed. “Std” = test standard as printed (NOT STATED where the TDS gives none). Every frame that shows data carries the footnote `Source: <product> TDS, <doc code>, <date>`; **date is NOT STATED because no DCP PDF prints one.**\n\n")
L.append("| Scene | Product.key | Value shown | Std | Source file | Page | Doc code | Date |\n|---|---|---|---|---|---|---|---|\n")
shown_pending = []
n = 0
for b in T["beats"]:
    for k in b["keys"]:
        pid, key = k.split("."); e = byid[canon(pid)]["values"][key][0]
        val = "**Data pending**" if e["value"] == MISS else f"{e['value']} {e['unit']}".strip()
        if e["value"] == MISS: shown_pending.append((b["id"], k))
        L.append(f"| {b['id']} | `{k}` | {val} | {e['test_standard']} | `{e['source_file']}` | {e['page'] if e['page'] else '—'} | {e['doc_code']} | {e['doc_date']} |\n")
        n += 1
L.append(f"\n{n} value placements on screen (some values repeat across scenes).\n\n")

L.append("### 2b. TDS / method-statement wording shown on screen (callouts, “Choose … when”)\n\n| Chapter | Product | Text | Page | Source |\n|---|---|---|---|---|\n")
for c in CH:
    for x in c["callouts"]:
        L.append(f"| {c['ch']} callout | {x['product']} | “{x['quote']}” | {x['page']} | {x['source']} |\n")
    for x in c["choose"]:
        pr = byid[canon(x["product"])]
        L.append(f"| {c['ch']} choose | {x['product']} | “{x['quote']}” | {x['page']} | {pr['name']} TDS, {pr['doc_code']}, {pr['doc_date']} |\n")

L.append("\n### 2c. Selector matrix (Ch9) — ticks\n\nA tick appears only where a TDS use line maps to the zone (`uses[]` in products.json; quote + page for each).\n\n| Product | Zones ticked | Other TDS-listed uses shown as text |\n|---|---|---|\n")
for r in SEL["rows"]:
    L.append(f"| {r['name']} | {', '.join(r['zones']) or '—'} | {'; '.join(r['other_listed_uses']) or '—'} |\n")

# ---- 3 open items
L.append("\n## 3. Open items ([DATA REQUIRED — R&D])\n\n")
L.append("**Shown on screen as grey “Data pending” tags:**\n\n")
if shown_pending:
    for s, k in shown_pending: L.append(f"- scene {s}: `{k}`\n")
else:
    L.append("- none\n")
L.append("\n**Full list of missing values and decisions:** see `qa/open_items.md` (generated). Summary of what is still outstanding from DCP/you:\n")
L.append("- Document **dates** (no PDF prints one) → every footnote reads `NOT STATED`.\n- Missing documents: **Repcoat P Ultra** TDS (named by method statements); method statements for PU-P100, Setseal 300C, Repcoat, Repcoat FF Plus, primers/DPM.\n- Missing values: see `qa/open_items.md` table B (e.g. VOC for PU-P150/P100/H50, Setseal 300C; carbonation value for Repcoat FF Plus).\n- DCP full brand palette (only the two logo colours are known).\n- Arabic: `src/i18n/ar.json` is a key-complete shell with empty values.\n\n")

# ---- 4 conflicts
L.append("## 4. Conflicts between DCP documents\n\nNeither value is chosen; affected values are **held off screen** (`on_screen_allowed: false` in products.json; `npm run validate` fails if one is used).\n\n")
held = [(p["id"], k, v[0]["held_conflict"]) for p in P["products"] for k, v in p["values"].items() if v[0].get("held_conflict")]
L.append("Held data keys: " + ", ".join(f"`{a}.{b}` ({c})" for a, b, c in held) + "\n\n")
conf = open(f"{ROOT}/qa/conflicts.md").read().split("\n", 2)[2]
L.append(conf.replace("\n## ", "\n### ") + "\n")

# ---- 5 assumptions
L.append("## 5. Assumptions (all labelled ASSUMED)\n\n")
A = [
 "ASSUMED: the Qatar-site (dcp-int.com/qa) documents are the baseline; other regional revisions of the same products were not downloaded or compared.",
 "ASSUMED: coverage is shown exactly as printed (kg/m², litre/m², m²/kg, m²/ltr) — never converted — because brief §3.3 forbids conversion and §3.4 asks for m²/kg or m²/ltr.",
 "ASSUMED: swimming pools / aquariums map to zone D (water-retaining structures) — you confirmed this.",
 "ASSUMED: car-park lines stay as listed uses in the selector’s “Other TDS-listed uses” column (no car-park zone exists) — your “should stay” reading.",
 "ASSUMED: PRIMER_NAMING = \"legacy\" (default); primer names are shown as each TDS prints them (PU-P150 names DonProof Primer EP; PU-P60/P100/H50 name Strongcoat Primer Range).",
 "ASSUMED: DonProof AL is the “aliphatic PU topcoat” of the brief (it is the only TDS describing itself as an aliphatic polyurethane topcoat for polyurea).",
 "ASSUMED: the Repcoat P TDS you uploaded is the same document already held; whether Repcoat P Ultra is the same product is unconfirmed.",
 "ASSUMED: the DCP logo file on dcp-int.com is the approved master; its two printed colours are the only brand colours (#F06C38, #211D22). The rest of the palette is a neutral placeholder.",
 "ASSUMED: product-family colours (spray blue, sheet green, liquid violet, epoxy ochre, cementitious slate, protective-coating rose, accessory cyan) are acceptable placeholders.",
 "ASSUMED: the isometric building and every layer stack are schematic (not to scale); layer thicknesses on screen are not the TDS thicknesses.",
 "ASSUMED: for the PU-P150 build-up the primer is DonProof Primer EP (the PU-P150 TDS names it for concrete); its spread rate is held back (conflict C-08), so the primer layer shows no value.",
 "ASSUMED: in the bar panels, mixed “≥ / ± / >” qualifiers are shown exactly as printed; bars use only the first printed number for length. Qualifiers differ between products (e.g. PU-P60 elongation “400 ± 50 %” vs “≥ 300 %”).",
 "ASSUMED: EPW-P and EPW-S share one TDS, so their data is stored once; the EPW chemical-resistance rows are the only per-grade differences shown.",
 "ASSUMED: swimming-pool / car-park uses and the HS “tunnelling” use are shown only as TDS wording where listed; the selector ticks come from the zone mapping in products.json.",
 "ASSUMED: voice-over timing — scene lengths are set from the script at ≤ 2.7 words/s; a recorded VO may need small edits.",
 "ASSUMED: matrix pages (10 rows each) are the way to keep text ≥ 36 px; the “Other TDS-listed uses” column is truncated with an ellipsis where long.",
 "ASSUMED: Ch0 and Ch1 show no data values, so they carry no source footnote.",
 "ASSUMED: chapter markers are written as MP4 chapters (QuickTime text track) and named from `src/i18n/en.json → chapters`.",
 "ASSUMED: the end card shows placeholders for contact details; the logo is the website SVG.",
]
for a in A: L.append(f"- {a}\n")

# ---- 6 checklist
L.append("\n## 6. Brief compliance checklist\n\n| Brief item | Status |\n|---|---|\n")
C = [
 ("§3.1–3.2 values from /source-tds in products.json with {value, unit, test_standard, source_file, page, doc_code, doc_date}", "Done; page located by script; NOT STATED where no date/code"),
 ("§3.3 no estimates/conversions; missing = [DATA REQUIRED — R&D] shown as grey tag", "Done (DataPending component)"),
 ("§3.4 SI units, full standard designations as printed", "Done (as printed; coverage per ASSUMED note)"),
 ("§3.5 conflicts logged, value off screen", "Done (qa/conflicts.md; validate enforces)"),
 ("§3.6 validate fails on unsourced value / mixed-standard chart / product in unlisted zone", "Done and tested with deliberate breakages"),
 ("§3.7 no claims beyond TDS, no service-life/best/No.1/competitors", "Banned-wording scan in validate; none present"),
 ("§3.8 footnote on every data frame", "Done"),
 ("§4 scope boundaries (no car-park deck/PMMA, crystalline, Strongcoat floor systems)", "HB/HB400 dropped. Setseal R (crystalline) kept at your instruction. Car-park lines shown only as listed text."),
 ("§5 chapter structure Ch0–Ch10, same beat pattern per zone", "Done"),
 ("§6 ≤3 products & ≤4 properties per panel; bars only for same standard; no scores", "Done and enforced"),
 ("§7 flat/isometric linework, one colour per family, one sans family, body ≥ 36 px, 5% safe margins, free lower third", "Done; footnote (24 px) sits at the bottom edge; SelectorMatrix legend/other-uses text at 36 px"),
 ("§2 npm scripts validate, render:master, render:chapters, stills", "Done"),
 ("§2 RTL-ready; text via i18n keys", "Done; Arabic strings not written"),
 ("§1 master 4–5 min, 1080p30 H.264 + chapter markers, per-chapter MP4s, separate SRT, no burned-in captions", "Done (see section 1)"),
 ("§1 vertical cutdowns", "Pending your approval of the master"),
]
for a, b in C: L.append(f"| {a} | {b} |\n")
open(f"{ROOT}/qa/qa_report.md", "w").write("".join(L))
print("qa_report.md written;", n, "value placements,", len(shown_pending), "data-pending placements")
